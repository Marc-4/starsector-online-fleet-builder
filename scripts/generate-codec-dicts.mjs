#!/usr/bin/env node
// Generates src/lib/fleetDicts.ts — static hull/weapon id tables for the v3 fleet hash.
// Rerun after adding modded hulls/weapons: `npm run generate:dicts`
import { readdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, "..")
const shipDataDir = path.join(root, "src/shipData")
const skinsDir = path.join(shipDataDir, "skins")
const weaponDataDir = path.join(root, "src/weaponData")
const outFile = path.join(root, "src/lib/fleetDicts.ts")

async function basenames(dir, ext) {
  try {
    const entries = await readdir(dir, { withFileTypes: true })
    return entries.filter((e) => e.isFile() && e.name.endsWith(ext)).map((e) => path.basename(e.name, ext))
  } catch {
    return []
  }
}

// Minimal CSV parser (handles quoted fields with commas) — returns rows as string[][]
function parseCsv(text) {
  const rows = []
  let row = []
  let field = ""
  let inQuotes = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"'
          i++
        } else inQuotes = false
      } else field += c
    } else if (c === '"') inQuotes = true
    else if (c === ",") {
      row.push(field)
      field = ""
    } else if (c === "\n") {
      row.push(field)
      field = ""
      rows.push(row)
      row = []
    } else if (c === "\r") {
      // skip, handled by \n
    } else field += c
  }
  if (field !== "" || row.length > 0) {
    row.push(field)
    rows.push(row)
  }
  return rows.filter((r) => r.length > 0 && r.some((c) => c.trim() !== ""))
}

const sortIds = (ids) => [...new Set(ids.filter((s) => typeof s === "string" && s.trim() !== ""))].sort((a, b) => a.localeCompare(b))

// --- hulls: hullId from each .ship file + skinHullId from each .skin file + manifest names ---
const hullIds = []
for (const name of await basenames(shipDataDir, ".ship")) {
  try {
    const raw = await readFile(path.join(shipDataDir, `${name}.ship`), "utf8")
    const m = raw.match(/"hullId"\s*:\s*"([^"]+)"/)
    if (m) hullIds.push(m[1])
    else hullIds.push(name)
  } catch {
    hullIds.push(name)
  }
}
for (const name of await basenames(skinsDir, ".skin")) {
  try {
    const raw = await readFile(path.join(skinsDir, `${name}.skin`), "utf8")
    const m = raw.match(/"skinHullId"\s*:\s*"([^"]+)"/)
    if (m) hullIds.push(m[1])
  } catch {
    /* ignore */
  }
}
try {
  const manifest = JSON.parse(await readFile(path.join(shipDataDir, "manifest.json"), "utf8"))
  if (Array.isArray(manifest)) hullIds.push(...manifest)
} catch {
  /* ignore */
}

// --- weapons: .wpn basenames + weapon_data.csv ids ---
const weaponIds = await basenames(weaponDataDir, ".wpn")
try {
  const rows = parseCsv(await readFile(path.join(weaponDataDir, "weapon_data.csv"), "utf8"))
  const header = rows[0].map((h) => h.trim().toLowerCase())
  const idCol = header.indexOf("id")
  if (idCol >= 0) for (const r of rows.slice(1)) if (r[idCol]) weaponIds.push(r[idCol].trim())
} catch {
  /* ignore */
}

// --- wings: wing_data.csv ids ---
const wingIds = []
try {
  const rows = parseCsv(await readFile(path.join(shipDataDir, "wing_data.csv"), "utf8"))
  const header = rows[0].map((h) => h.trim().toLowerCase())
  const idCol = header.indexOf("id")
  if (idCol >= 0) for (const r of rows.slice(1)) if (r[idCol]) wingIds.push(r[idCol].trim())
} catch {
  /* ignore */
}

const HULL_IDS = stableMerge(await readExisting(outFile, "HULL_IDS"), sortIds(hullIds))
const WEAPON_IDS = stableMerge(await readExisting(outFile, "WEAPON_IDS"), sortIds(weaponIds))
const WING_IDS = stableMerge(await readExisting(outFile, "WING_IDS"), sortIds(wingIds))

// Preserve existing indexes so previously shared links keep decoding:
// existing ids stay in place, only unseen ids are appended (sorted).
async function readExisting(file, name) {
  try {
    const text = await readFile(file, "utf8")
    const m = text.match(new RegExp(`${name}: string\\[\\] = (\\[[\\s\\S]*?\\])`))
    if (m) {
      const arr = JSON.parse(m[1])
      if (Array.isArray(arr)) return arr.filter((s) => typeof s === "string")
    }
  } catch {
    /* first run */
  }
  return []
}

function stableMerge(existing, fresh) {
  const seen = new Set(existing)
  const added = fresh.filter((id) => !seen.has(id))
  return [...existing, ...added]
}

const content = `// GENERATED by scripts/generate-codec-dicts.mjs — do not edit.
// Rerun with \`npm run generate:dicts\` after adding modded hulls/weapons.
// Sorted id tables for the v3 fleet hash. Ids are encoded as indexes;
// unknown ids fall back to inline strings, so old/new tables stay decodable.
// IMPORTANT: existing entries are never reordered — new ids are appended,
// so hashes shared earlier keep decoding after regeneration.
export const HULL_IDS: string[] = ${JSON.stringify(HULL_IDS)}
export const WEAPON_IDS: string[] = ${JSON.stringify(WEAPON_IDS)}
export const WING_IDS: string[] = ${JSON.stringify(WING_IDS)}
`

await writeFile(outFile, content, "utf8")
console.log(`Wrote ${HULL_IDS.length} hulls + ${WEAPON_IDS.length} weapons + ${WING_IDS.length} wings to ${path.relative(process.cwd(), outFile)}`)
